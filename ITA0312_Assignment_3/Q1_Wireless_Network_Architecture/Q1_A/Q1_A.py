import os
import csv
import random
import numpy as np
import matplotlib.pyplot as plt
from matplotlib.patches import FancyBboxPatch

random.seed(42)
np.random.seed(42)

os.makedirs("Q1_Wireless_Network_Architecture/graphs", exist_ok=True)
os.makedirs("Q1_Wireless_Network_Architecture/results", exist_ok=True)
os.makedirs("Q1_Wireless_Network_Architecture/diagrams", exist_ok=True)

# Network components
mobile_node = "Mobile Node"
access_point = "Wireless Access Point"
router = "Router"
server = "Server"

# Network configuration
total_packets = 30
packet_size = 1024
bandwidth_mbps = 10
base_delay = 10
packet_loss_probability = 0.08

# Create wireless network architecture diagram
fig, ax = plt.subplots(figsize=(11, 4))
ax.set_xlim(0, 11)
ax.set_ylim(0, 4)
ax.axis("off")

nodes = [
    (0.5, 1.5, "Mobile Node"),
    (3.2, 1.5, "Wireless AP"),
    (6.0, 1.5, "Router"),
    (8.7, 1.5, "Server")
]

for x, y, label in nodes:
    box = FancyBboxPatch(
        (x, y), 1.7, 0.9,
        boxstyle="round,pad=0.15",
        edgecolor="black",
        facecolor="lightblue"
    )
    ax.add_patch(box)
    ax.text(x + 0.85, y + 0.45, label,
            ha="center", va="center", fontsize=10)

for x1, x2 in [(2.2, 3.2), (4.9, 6.0), (7.7, 8.7)]:
    ax.annotate(
        "", xy=(x2, 1.95), xytext=(x1, 1.95),
        arrowprops=dict(arrowstyle="->", linewidth=2)
    )

ax.text(2.7, 2.7, "Wireless Link", ha="center", fontsize=9)
ax.text(5.45, 2.7, "Wired Link", ha="center", fontsize=9)
ax.text(8.2, 2.7, "Wired Link", ha="center", fontsize=9)

ax.set_title("Infrastructure-Based Wireless Network Architecture")
plt.savefig(
    "Q1_Wireless_Network_Architecture/diagrams/wireless_architecture.png",
    bbox_inches="tight"
)
plt.show()

# Simulate packet transmission
results = []
delays = []
successful = 0
failed = 0

transmission_time = (packet_size * 8 / (bandwidth_mbps * 1_000_000)) * 1000

for packet_id in range(1, total_packets + 1):
    jitter = random.uniform(2, 8)
    delay = base_delay + transmission_time + jitter

    if random.random() >= packet_loss_probability:
        status = "Delivered"
        successful += 1
        delays.append(delay)
    else:
        status = "Lost"
        failed += 1

    results.append([packet_id, status, round(delay, 2)])

# Calculate performance metrics
pdr = (successful / total_packets) * 100
loss_rate = (failed / total_packets) * 100
average_delay = np.mean(delays) if delays else 0

# Save packet-level results
csv_path = "Q1_Wireless_Network_Architecture/results/packet_results.csv"

with open(csv_path, "w", newline="") as file:
    writer = csv.writer(file)
    writer.writerow(["Packet ID", "Status", "Delay (ms)"])
    writer.writerows(results)

# Display results
print("WIRELESS NETWORK SIMULATION")
print("-" * 40)
print("Mobile Node -> Wireless AP -> Router -> Server")
print("Total Packets:", total_packets)
print("Successful Packets:", successful)
print("Lost Packets:", failed)
print("Packet Delivery Ratio:", round(pdr, 2), "%")
print("Packet Loss Rate:", round(loss_rate, 2), "%")
print("Average Delay:", round(average_delay, 2), "ms")

# Save summary
summary_path = "Q1_Wireless_Network_Architecture/results/simulation_summary.txt"

with open(summary_path, "w") as file:
    file.write("WIRELESS NETWORK SIMULATION RESULTS\n")
    file.write("-----------------------------------\n")
    file.write(f"Total Packets: {total_packets}\n")
    file.write(f"Successful Packets: {successful}\n")
    file.write(f"Lost Packets: {failed}\n")
    file.write(f"Packet Delivery Ratio: {pdr:.2f}%\n")
    file.write(f"Packet Loss Rate: {loss_rate:.2f}%\n")
    file.write(f"Average Delay: {average_delay:.2f} ms\n")
    file.write(f"Bandwidth: {bandwidth_mbps} Mbps\n")

# Generate performance graphs
fig, axes = plt.subplots(1, 2, figsize=(12, 4))

axes[0].bar(
    ["Delivered", "Lost"],
    [successful, failed],
    color=["green", "red"]
)
axes[0].set_title("Packet Delivery Analysis")
axes[0].set_ylabel("Number of Packets")

axes[1].plot(
    range(1, len(delays) + 1),
    delays,
    marker="o"
)
axes[1].set_title("Transmission Delay")
axes[1].set_xlabel("Successfully Delivered Packet")
axes[1].set_ylabel("Delay (ms)")
axes[1].grid(True)

plt.tight_layout()
plt.savefig(
    "Q1_Wireless_Network_Architecture/graphs/performance_graphs.png"
)
plt.show()

print("\nFiles generated successfully.")

